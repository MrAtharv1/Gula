export function getTranslations(lang: AppLanguage): TranslationKeys {
  return { ...EN, ...(TRANSLATIONS[lang] || {}) };
}

export function getLocalizedPanelName(
  category: MetricCategory | string,
  lang: AppLanguage
): string {
  const t = getTranslations(lang);
  const key = `panel_${category}` as keyof TranslationKeys;
  return (t[key] as string) || category;
}

export function getLocalizedFlagLabel(flag: ResultFlag, lang: AppLanguage): string {
  const t = getTranslations(lang);
  if (flag === "high") return t.flagHigh;
  if (flag === "low") return t.flagLow;
  if (flag === "borderline") return t.flagBorderline;
  return t.flagNormal;
}

export function useTranslation() {
  const language = usePreferenceStore((s) => s.language);
  const setLanguage = usePreferenceStore((s) => s.setLanguage);
  const t = getTranslations(language);
  const currentLangOption =
    APP_LANGUAGES.find((l) => l.code === language) || APP_LANGUAGES[0];

  return { t, language, setLanguage, currentLangOption };
}
